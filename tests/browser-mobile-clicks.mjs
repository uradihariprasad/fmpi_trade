import { chromium } from "playwright";
const url = process.env.TEST_URL ?? "http://127.0.0.1:3102";
const browser = await chromium.launch({ headless: true });
const page = await browser.newPage({ viewport: { width: 390, height: 844 }, isMobile: true, hasTouch: true });
const errors = [];
page.on("pageerror", e => { errors.push(`PAGEERROR ${e.stack ?? e.message}`); console.error(errors.at(-1)); });
page.on("console", m => { if (m.type() === "error") { errors.push(`CONSOLE ${m.text()}`); console.error(errors.at(-1)); } });
await page.goto(url, { waitUntil: "domcontentloaded", timeout: 60_000 });
await page.waitForSelector("header", { state: "visible", timeout: 60_000 });
await page.waitForFunction(() => !document.body.innerText.includes("fetching genuine"), null, { timeout: 120_000 }).catch(()=>{});
const act = async (name, fn) => { try { await fn(); await page.waitForTimeout(250); console.log(`PASS ${name}`); } catch(e) { errors.push(`${name}: ${e.message}`); console.error(`FAIL ${name}: ${e.message}`); } };
await act("mobile chart touch", () => page.locator("canvas").first().tap({ position: { x: 170, y: 140 } }));
await act("mobile 10m", () => page.getByRole("button", { name: "10 MIN" }).tap());
await act("mobile 5m", () => page.getByRole("button", { name: "5 MIN" }).tap());
await act("open drawer", () => page.getByRole("button", { name: "Open instrument list" }).tap());
const drawer = page.locator('[aria-hidden="false"]').filter({ has: page.getByRole("button", { name: /^TRADES$/ }) });
await act("drawer TOP 10", () => drawer.getByRole("button", { name: /TOP 10/ }).click());
await act("drawer ALL", () => drawer.getByRole("button", { name: /^ALL$/ }).click());
await act("drawer NIFTY", () => drawer.getByRole("button", { name: /^NIFTY\b/ }).first().click());
await act("login open", () => page.getByRole("button", { name: "Upstox session" }).tap());
await act("login close", () => page.getByRole("button", { name: "Close", exact: true }).tap());
for (const name of ["STATE","ZONES","EVIDENCE","METHOD"]) await act(`mobile ${name}`, () => page.getByRole("button", { name: new RegExp(`^${name}$`) }).tap());
const body = await page.locator("body").innerText();
if (/This page couldn.t load|Reload to try again/i.test(body)) errors.push("FATAL UI error page displayed");
console.log(`FINAL ${page.url()} chars=${body.length} errors=${errors.length}`);
if (errors.length) console.log(errors.join("\n---\n"));
await browser.close();
process.exit(errors.length ? 1 : 0);
